    function initMap(lat1, lon1, lat2, lon2, name1, name2) {
      const mapBox = document.getElementById("mapContainer");
      if (!mapBox) return;

      if (mapInstance) {
        mapInstance.remove();
        mapInstance = null;
      }

      mapInstance = L.map('mapContainer').setView([lat1, lon1], 10);

      L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        attribution: '© OpenStreetMap contributors'
      }).addTo(mapInstance);

      L.marker([lat1, lon1]).addTo(mapInstance)
        .bindPopup(`<b>${name1} (${t("myLocation")})</b><br>${ROLE === 'farmer' ? 'Farm Location' : 'Worker Location'}`)
        .openPopup();

      L.marker([lat2, lon2]).addTo(mapInstance)
        .bindPopup(`<b>${name2}</b><br>${ROLE === 'farmer' ? 'Nearby Labour' : 'Hiring Farmer Field'}`);

      const routeLine = L.polyline([[lat1, lon1], [lat2, lon2]], { color: '#166e34', weight: 4, dashArray: '6, 8' }).addTo(mapInstance);
      mapInstance.fitBounds(routeLine.getBounds(), { padding: [40, 40] });
    }

    function detectLiveGPS() {
      if (!navigator.geolocation) {
        toast("Geolocation is not supported by your browser.");
        return;
      }

      toast("Detecting your live coordinates via GPS...");
      navigator.geolocation.getCurrentPosition(
        (pos) => {
          const lat = pos.coords.latitude;
          const lng = pos.coords.longitude;
          const p = getCurrentProfile();
          p.lat = lat;
          p.lng = lng;
          saveCurrentProfile(p);
          toast(`✓ GPS Acquired: ${lat.toFixed(4)}, ${lng.toFixed(4)}`);
          profilePage();
        },
        (err) => {
          toast("Unable to retrieve GPS: " + err.message);
        },
        { enableHighAccuracy: true, timeout: 10000 }
      );
    }

