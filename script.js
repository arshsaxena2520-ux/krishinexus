    function markJobComplete(bookingId, labourId) {
      const b = BOOKINGS.find(x => x.id === bookingId);
      if (b) b.status = "Completed";
      const l = LABOURS.find(x => x.id === labourId);
      if (l) {
        l.completed = (l.completed || 0) + 1;
        l.availability = "Available";
      }
      syncStorage();
      toast("Job marked as completed. Please leave a rating.");
      go("ratings");
    }

