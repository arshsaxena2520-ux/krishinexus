    function confirmBooking(labourId) {
      const farmerId = Number(document.getElementById("bookFarmerId").value);
      const work = document.getElementById("bookWork").value;
      const date = document.getElementById("bookDate").value;

      BOOKINGS.unshift({
        id: Date.now(),
        farmerId,
        labourId,
        work,
        date,
        status: "Confirmed"
      });
      syncStorage();
      closeModal();
      toast("Work confirmation sent to labour!");
      go("bookings");
    }

