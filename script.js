    function submitReview() {
      const labour = document.getElementById("reviewLabourSelect").value;
      const rating = Number(document.getElementById("selectedStarRating").value) || 5;
      const comment = document.getElementById("reviewComment").value.trim();

      if (!comment) {
        toast("Please enter a short comment.");
        return;
      }

      REVIEWS.unshift({ labour, rating, comment });
      syncStorage();
      toast("Rating submitted successfully! ⭐");
      ratingsPage();
    }

